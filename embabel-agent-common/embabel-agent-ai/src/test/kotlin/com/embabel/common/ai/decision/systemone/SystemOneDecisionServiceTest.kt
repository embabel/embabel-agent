                                assertTrue(failure.message!!.length <= 128)
                                assertNull(failure.cause)
                                assertEquals(0, credentials.get())
                                assertEquals(0, server.calls.get())
                            } })
                        }
                    }
                SystemOneModelFactory("systemone", "SystemOne", options, listOf("alias"),
                    tokenSupplier = java.util.function.Supplier { credentials.incrementAndGet(); "PRIVATE_TOKEN" }, profile = profile)
                    .use { factory ->
                        assertThrows<UnsupportedDecisionException> { factory.create("alias").ask(input, spec) }
                        assertEquals(0, credentials.get())
                        assertEquals(0, server.calls.get())
                    }
            }
        }


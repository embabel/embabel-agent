        fun `decoded root seam preserves raw response answers provenance and metadata bounds`() {
            val request = DecisionRequest.of("input", spec)
            val headers = mapOf("x-profile" to listOf("value"))
            val profile = object : SystemOneModelProfile {
                override fun provenance(metadata: SystemOneResponseMetadata): ModelProvenance {
                    assertEquals("alias", metadata.requestedModel)
                    assertEquals("openjev-fixture", metadata.actualModel)
                    assertEquals(100L, metadata.inputTokens)
                    assertEquals(0L, metadata.outputTokens)
                    assertEquals(headers, metadata.headers)
                    return ModelProvenance(metadata.actualModel, "custom", "v1", "request-1")
                }
            }
            val body = SystemOneTestServer.fixture().toByteArray(UTF_8)
            val raw = SystemOneCodec.decode("alias", request, SystemOneHttpResponse(body, headers), profile)
            val decoded = SystemOneCodec.decode("alias", request, SystemOneCodec.read(body), headers, profile)

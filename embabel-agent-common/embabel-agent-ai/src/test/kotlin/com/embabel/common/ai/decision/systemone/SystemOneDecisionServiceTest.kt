            assertEquals(raw.answer(choice), decoded.answer(choice))
            assertEquals(raw.choiceDistribution(choice), decoded.choiceDistribution(choice))
            assertEquals(raw.answer(rating), decoded.answer(rating))
            assertThrows<IllegalArgumentException> {
                SystemOneCodec.decode("alias", request, SystemOneCodec.read(body), mapOf("x-private" to listOf("x".repeat(8193))), profile)
            }
        }


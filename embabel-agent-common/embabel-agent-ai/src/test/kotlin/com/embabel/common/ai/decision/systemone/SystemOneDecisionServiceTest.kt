class SystemOneDecisionServiceTest {
    private val proposition = Questions.named("public-proposition").proposition("Is this true?").build()
    private val choice = Questions.named("public-choice").choice("Choose one")
        .option("one", "One").option("two", "Two").build()
    private val rating = Questions.named("public-rating").rating("Rate this")
        .level("low", "Low").level("high", "High").build()
    private val spec = DecisionSpec.of(proposition, choice, rating)

    @Nested
    inner class Evidence {
        @Test
        fun `actual pinned OpenJev codec preserves independent confidence and all evidence`() {
            // Generated by actual pure confidence/to_answer functions from OpenJev commit
            // 75f22b6dad8c360fdba0e0ebd3dc0a1187628f60, engine.py SHA256
            // e084734f969b414be701bc438617c302e0b44867d907956ec87dcafc66b1d089.
            // TypeSafe OpenAPI 0.2.0 SHA256 a191f8a7df6bd6fedced8120dd0fd106f88575d1d1c8360d08900a6c7c0360d5.
            // Codec compatibility evidence only: no model, tokenizer or engine was loaded.
            SystemOneTestServer().use { server -> server.factory().use { factory ->
                val service = factory.create("alias")
                val response = service.ask("input", spec)
                val assessed = response.answer(proposition) as PropositionResult.Answered
                assertEquals(0.6, assessed.pTrue)
                assertEquals("openjev-fixture", assessed.provenance.modelName)
                val selected = response.answer(choice) as ClassificationResult.Selected
                assertEquals("one", selected.categoryId)
                assertEquals(0.029049405545331197, selected.confidence)
                assertNotEquals(0.6, selected.confidence)
                assertEquals(listOf(CategoryProbability("one", 0.6), CategoryProbability("two", 0.4)),
                    response.choiceDistribution(choice)!!.probabilities)
                val scored = response.answer(rating) as RatingResult.Answered
                assertNull(scored.selectedLevelId)
                assertEquals(RatingScore(0.75, RatingStatistic.EXPECTED_LEVEL_INDEX), scored.score)
                assertEquals(listOf(LevelProbability("low", 0.25), LevelProbability("high", 0.75)), scored.distribution)
                assertEquals(0.18872187554086717, scored.confidence)
                assertEquals(1, server.calls.get())
            } }
        }

        @Test
        fun `zero confidence and tied selected argmax remain a selection with unmodified probabilities`() {
            val body = SystemOneTestServer.fixture().replace("\"one\": 0.6", "\"one\": 0.5")
                .replace("\"two\": 0.4", "\"two\": 0.5")
                .replace("0.029049405545331197", "0.0")
            SystemOneTestServer(body).use { server -> server.factory().use { factory ->
                val response = factory.create("alias").ask("input", spec)
                assertEquals(0.0, (response.answer(choice) as ClassificationResult.Selected).confidence)
                assertEquals(listOf(0.5, 0.5), response.choiceDistribution(choice)!!.probabilities.map { it.probability })
            } }
        }

        @Test
        fun `exact half noul is inconclusive and the existing type cannot retain half pTrue`() {
            SystemOneTestServer(SystemOneTestServer.fixture().replace("\"noul\": 0.6", "\"noul\": 0.5"))
                .use { server -> server.factory().use { factory ->
                    val result = factory.create("alias").ask("input", spec).answer(proposition)
                    assertTrue(result is PropositionResult.Inconclusive)
                    assertFalse(JsonMapper.builder().build().writeValueAsString(result).contains("pTrue"))
                } }
            SystemOneTestServer(SystemOneTestServer.fixture().replace("\"noul\": 0.6", "\"noul\": 0.2"))
                .use { server -> server.factory().use { factory ->
                    val result = factory.create("alias").ask("input", spec).answer(proposition) as PropositionResult.Answered
                    assertFalse(result.answer)
                    assertEquals(0.2, result.pTrue)
                } }
        }

        @Test
        fun `more than nine hostile public question ids map in order to padded wire ids`() {
            val questions = (1..12).map { Questions.named("私密-\"\\-$it").proposition("question-$it").build() }
            val answers = (1..12).associate { "q%03d".format(it) to mapOf("type" to "noul", "noul" to 0.6) }
            val body = JsonMapper.builder().build().writeValueAsString(mapOf("model" to "actual", "answers" to answers,
                "usage" to mapOf("input_tokens" to 0, "output_tokens" to 0)))
            SystemOneTestServer(body).use { server -> server.factory().use { factory ->
                val response = factory.create("alias").ask("input", DecisionSpec.of(questions))
                assertEquals(questions.map { it.name }, response.answers.map { it.name })
                val sent = JsonMapper.builder().build().readTree(server.requests.single())
                assertEquals((1..12).map { "q%03d".format(it) }, sent.get("questions").propertyNames().toList())
                assertEquals("alias", sent.get("model").asText())
                assertFalse(server.requests.single().contains("私密"))
            } }
        }

        @Test
        fun `choice ids remain public keys and score blank descriptions fall back to ids`() {
            val hostile = "公\"\\选"
            val c = Questions.named("choice").choice("choose").option(hostile, "one").option("other", "two").build()
            val score = Questions.named("rating").rating("rate").level("empty", "").level("other", "High").build()
            val body = JsonMapper.builder().build().writeValueAsString(mapOf("model" to "actual", "usage" to
                mapOf("input_tokens" to 0, "output_tokens" to 0), "answers" to mapOf(
                "q001" to mapOf("type" to "choice", "choice" to hostile, "confidence" to 0.0,
                    "probabilities" to mapOf(hostile to 0.6, "other" to 0.4)),
                "q002" to mapOf("type" to "score", "score" to 0.75, "confidence" to 0.0,
                    "legend" to mapOf("0" to "empty", "1" to "High"), "probabilities" to mapOf("0" to 0.25, "1" to 0.75)))))
            SystemOneTestServer(body).use { server -> server.factory().use { factory ->
                val response = factory.create("alias").ask("input", DecisionSpec.of(c, score))
                assertEquals(hostile, (response.answer(c) as ClassificationResult.Selected).categoryId)
                val sent = JsonMapper.builder().build().readTree(server.requests.single()).get("questions")
                assertEquals(setOf(hostile, "other"), sent.get("q001").get("criteria").propertyNames().toSet())
                assertEquals("empty", sent.get("q002").get("criteria").get(0).asText())
                assertNull((response.answer(score) as RatingResult.Answered).selectedLevelId)
            } }
        }
    }

    @Test
    fun `each typed hook and whole ask retain real observation behavior`() {
        val registry = ObservationRegistry.create()
        val stopped = mutableListOf<String>()
        registry.observationConfig().observationHandler(object : ObservationHandler<Observation.Context> {
            override fun supportsContext(context: Observation.Context) = true
            override fun onStop(context: Observation.Context) { stopped += requireNotNull(context.name) }
        })
        SystemOneTestServer().use { server ->
            val mapper = JsonMapper.builder().build()
            server.handler = { exchange ->
                val type = mapper.readTree(server.requests.last()).get("questions").get("q001").get("type").stringValue()
                val key = when (type) { "choice" -> "q002"; "score" -> "q003"; else -> "q001" }
                val answer = mapper.readTree(SystemOneTestServer.fixture()).get("answers").get(key)
                server.respond(exchange, mapper.writeValueAsString(mapOf("model" to "actual", "answers" to mapOf("q001" to answer),
                    "usage" to mapOf("input_tokens" to 0, "output_tokens" to 0))))
            }
            SystemOneModelFactory("systemone", "SystemOne", SystemOneClientOptions(server.uri()), listOf("alias"), registry)
                .use { factory ->
                    val service = factory.create("alias")
                    assertTrue(service.assess(PropositionRequest("input", "true?")) is PropositionResult.Answered)
                    assertTrue(service.classify(ClassificationRequest.of("input", ClassificationSpec.builder().asking("choose")
                        .category("one", "One").category("two", "Two").build())) is ClassificationResult.Selected)
                    assertTrue((service as RatingAssessment).rate("input", rating) is RatingResult.Answered)
                    server.handler = { exchange -> server.respond(exchange, SystemOneTestServer.fixture()) }
                    assertNotNull(service.ask("input", spec).choiceDistribution(choice))
                    assertEquals(4, server.calls.get())
                    assertEquals(listOf("embabel.ai.decision", "embabel.ai.classification", "embabel.ai.decision",
                        "embabel.ai.decision", "embabel.ai.ask"), stopped)
                }
        }
    }


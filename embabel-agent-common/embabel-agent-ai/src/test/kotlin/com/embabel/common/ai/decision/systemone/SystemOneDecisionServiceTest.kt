            }
        }

        @Test
        fun `deadline also covers a server stalled before response headers`() {
            val release = CountDownLatch(1)
            SystemOneTestServer().use { server ->
                server.handler = { exchange -> release.await(2, TimeUnit.SECONDS); exchange.close() }
                server.factory(timeout = Duration.ofMillis(100)).use { factory ->
                    val start = System.nanoTime()
                    assertEquals(FailureReason.UNAVAILABLE, factory.create("alias").ask("input", spec).requestFailure)
                    assertTrue(Duration.ofNanos(System.nanoTime() - start) < Duration.ofSeconds(1))
                    release.countDown()
                }
            }
        }

        @Test
        fun `non success status does not parse bodies and profile may override status reason`() {
            listOf(400, 422, 409, 500, 502).forEach { status -> SystemOneTestServer("PRIVATE_ERROR", status).use { server ->
                server.factory().use { factory ->
                    val result = factory.create("alias").ask("input", spec)
                    assertEquals(if (status == 400 || status == 422) FailureReason.INVALID_RESPONSE else FailureReason.UNAVAILABLE,
                        result.requestFailure)
                    assertEquals(1, server.calls.get())
                }
            } }
            val profile = object : SystemOneModelProfile {
                override fun provenance(metadata: SystemOneResponseMetadata) = ModelProvenance(metadata.actualModel, "custom")
                override fun failureReason(statusCode: Int) = FailureReason.INVALID_RESPONSE
            }
            SystemOneTestServer("PRIVATE_ERROR", 502).use { server -> server.factory(profile = profile).use { factory ->
                assertEquals(FailureReason.INVALID_RESPONSE, factory.create("alias").ask("input", spec).requestFailure)
            } }
        }

        @Test
        fun `body and accepted metadata header excess are bounded invalid responses`() {
            SystemOneTestServer("x".repeat(10000)).use { server -> server.factory(maxResponse = 32).use { factory ->
                assertEquals(FailureReason.INVALID_RESPONSE, factory.create("alias").ask("input", spec).requestFailure)
            } }
            SystemOneTestServer().use { server ->
                server.handler = { exchange ->
                    exchange.responseHeaders.add("X-Private", "x".repeat(9000))
                    server.respond(exchange, SystemOneTestServer.fixture())
                }
                server.factory().use { factory ->
                    assertEquals(FailureReason.INVALID_RESPONSE, factory.create("alias").ask("input", spec).requestFailure)
                }
            }
        }

        @Test
        fun `deadline spans stalled streamed body and cancellation releases the call`() {
            val release = CountDownLatch(1)
            SystemOneTestServer().use { server ->
                server.handler = { exchange ->
                    exchange.sendResponseHeaders(200, 0)
                    exchange.responseBody.write('{'.code); exchange.responseBody.flush()
                    release.await(2, TimeUnit.SECONDS)
                    exchange.close()
                }
                server.factory(timeout = Duration.ofMillis(100)).use { factory ->
                    val start = System.nanoTime()
                    assertEquals(FailureReason.UNAVAILABLE, factory.create("alias").ask("input", spec).requestFailure)
                    assertTrue(Duration.ofNanos(System.nanoTime() - start) < Duration.ofSeconds(1))
                    release.countDown()
                    server.handler = { exchange -> server.respond(exchange, SystemOneTestServer.fixture()) }
                    assertNull(factory.create("alias").ask("input", spec).requestFailure)
                }
            }
        }

        @Test
        fun `interruption escapes with interrupt flag and no provider payload cause`() {
            val entered = CountDownLatch(1); val release = CountDownLatch(1)
            SystemOneTestServer().use { server ->
                server.handler = { exchange -> entered.countDown(); release.await(2, TimeUnit.SECONDS); exchange.close() }
                server.factory().use { factory ->
                    var failure: Throwable? = null; var interrupted = false
                    val caller = Thread {
                        try { factory.create("alias").ask("PRIVATE_INPUT", spec) }
                        catch (e: Throwable) { failure = e; interrupted = Thread.currentThread().isInterrupted }
                    }
                    caller.start(); assertTrue(entered.await(1, TimeUnit.SECONDS)); caller.interrupt(); caller.join(1000)
                    release.countDown()
                    assertFalse(caller.isAlive)
                    assertTrue(failure is CancellationException)
                    assertTrue(interrupted)
                    assertFalse(failure.toString().contains("PRIVATE_INPUT"))
                }
            }
        }

        @Test
        fun `redirect never forwards bearer credentials or retries to another server`() {
            SystemOneTestServer().use { target -> SystemOneTestServer().use { server ->
                server.handler = { exchange ->
                    exchange.responseHeaders.add("Location", target.uri().toString() + "PRIVATE_QUERY")
                    server.respond(exchange, "PRIVATE_BODY", 302)
                }
                server.factory(token = { "PRIVATE_TOKEN" }).use { factory ->
                    assertEquals(FailureReason.UNAVAILABLE, factory.create("alias").ask("input", spec).requestFailure)
                    assertEquals(1, server.calls.get()); assertEquals(0, target.calls.get())
                    assertFalse(factory.toString().contains("PRIVATE_TOKEN"))
                }
            } }
        }
    }
}

internal class SystemOneTestServer(var body: String = fixture(), var status: Int = 200) : AutoCloseable {
    private val executor = Executors.newCachedThreadPool { task -> Thread(task).apply { isDaemon = true } }
    val calls = AtomicInteger()
    val requests = CopyOnWriteArrayList<String>()
    val authorizations = CopyOnWriteArrayList<String>()
    private val server = HttpServer.create(InetSocketAddress("127.0.0.1", 0), 0)
    @Volatile var handler: (HttpExchange) -> Unit = { exchange -> respond(exchange, body, status) }
    init {
        server.executor = executor
        server.createContext("/") { exchange ->
            calls.incrementAndGet()
            requests += String(exchange.requestBody.readAllBytes(), UTF_8)
            authorizations += exchange.requestHeaders.getFirst("Authorization") ?: ""
            try { handler(exchange) } catch (_: Exception) { exchange.close() }
        }
        server.start()
    }
    fun uri(path: String = "/") = URI("http://127.0.0.1:${server.address.port}$path")
    fun factory(timeout: Duration = Duration.ofSeconds(45), maxResponse: Int = 65536,
                token: () -> String? = { null }, profile: SystemOneModelProfile? = null) =
        SystemOneModelFactory("systemone", "SystemOne", SystemOneClientOptions(uri(), timeout, 16384, maxResponse),
            listOf("alias"), tokenSupplier = java.util.function.Supplier { token() }, profile = profile)
    fun respond(exchange: HttpExchange, value: String, statusCode: Int = 200) {
        val bytes = value.toByteArray(UTF_8)
        exchange.responseHeaders.add("Content-Type", "application/json")
        exchange.sendResponseHeaders(statusCode, bytes.size.toLong())
        exchange.responseBody.use { it.write(bytes) }
        exchange.close()
    }
    override fun close() { server.stop(0); executor.shutdownNow() }
    companion object {
        fun fixture(): String = SystemOneTestServer::class.java.getResource("/decision/systemone/openjev-0.2.0-codec.json")!!.readText()
    }
}

    @Nested
    inner class Transport {
        @Test
        fun `closed transport is unavailable and status callback cancellation escapes`() {
            SystemOneTestServer().use { server ->
                val factory = server.factory()
                val service = factory.create("alias")
                factory.close()
                assertEquals(FailureReason.UNAVAILABLE, service.ask("input", spec).requestFailure)
                assertEquals(0, server.calls.get())
            }
            val cancelling = object : SystemOneModelProfile {
                override fun provenance(metadata: SystemOneResponseMetadata) = ModelProvenance(metadata.actualModel, "test")
                override fun failureReason(statusCode: Int): FailureReason = throw CancellationException("cancelled")
            }
            SystemOneTestServer("unread", 409).use { server -> server.factory(profile = cancelling).use { factory ->
                assertThrows<CancellationException> { factory.create("alias").ask("input", spec) }
            } }
        }

        @Test
        fun `request size and profile preflight fail before any socket call`() {
            SystemOneTestServer().use { server ->
                SystemOneModelFactory("systemone", "SystemOne", SystemOneClientOptions(server.uri(), maxRequestBytes = 32),
                    listOf("alias")).use { factory ->
                    assertEquals(FailureReason.INVALID_RESPONSE, factory.create("alias").ask("input".repeat(100), spec).requestFailure)
                    assertEquals(0, server.calls.get())
                }
                val rejecting = object : SystemOneModelProfile {
                    override fun validateRequest(request: DecisionRequest) { error("PRIVATE_INPUT") }
                    override fun provenance(metadata: SystemOneResponseMetadata): ModelProvenance = error("unreachable")
                }
                server.factory(profile = rejecting).use { factory ->

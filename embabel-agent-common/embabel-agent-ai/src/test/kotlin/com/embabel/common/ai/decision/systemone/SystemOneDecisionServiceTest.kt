        private fun assertInputRejected(maxRequestBytes: Int = 16384, input: String = "input",
                                        profile: SystemOneModelProfile = testProfile()) {
            SystemOneTestServer().use { server ->
                val credentials = AtomicInteger()
                val options = SystemOneClientOptions(server.uri(), maxRequestBytes = maxRequestBytes)
                SystemOneClient(options, java.util.function.Supplier { credentials.incrementAndGet(); "PRIVATE_TOKEN" }, profile)
                    .use { client ->
                        val direct = SystemOneDecisionService("alias", "SystemOne", client, profile)
                        val decorated = ObservedDecisionService(ObservedDecisionService(direct))
                        val request = DecisionRequest.of(input, spec)
                        val classification = ClassificationRequest.of(input, ClassificationSpec.builder().asking("choose")
                            .category("one", "One").category("two", "Two").build())
                        listOf<DecisionService>(direct, decorated).forEach { service ->
                            val calls: List<() -> Any> = listOf(
                                { service.ask(request) },
                                { (service as QuestionSetExecution).askQuestionSet(request) },
                                { service.classify(classification) },
                                { service.assess(PropositionRequest(input, "true?")) },
                                { (service as PropositionAssessment).assess(input, proposition) },
                                { (service as RatingAssessment).rate(input, rating) },
                            )
                            assertAll(calls.map { call -> org.junit.jupiter.api.function.Executable {
                                val failure = assertThrows<UnsupportedDecisionException> { call() }
